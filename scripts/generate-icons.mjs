const dir = "node_modules/@material-symbols/svg-400/outlined";
const lines = [
  "// Generated by scripts/generate-icons.mjs from Google Material Symbols (Apache-2.0). Do not edit.",
  'import type { SVGProps } from "react";',
  "",
  'export type IconProps = Omit<SVGProps<SVGSVGElement>, "children"> & { strokeWidth?: number | string };',
  "export type MaterialIcon = (props: IconProps) => React.JSX.Element;",
  "",
  "function make(name: string, d: string): MaterialIcon {",
  "  // eslint-disable-next-line @typescript-eslint/no-unused-vars",
  "  function Icon({ strokeWidth, className, ...props }: IconProps) {",
  "    return (",
  '      <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 -960 960 960" width={24} height={24} fill="currentColor"',
  '        className={["material-icon", className].filter(Boolean).join(" ")} data-icon={name} {...props}>',
  "        <path d={d} />",
  "      </svg>",
  "    );",
  "  }",
  "  Icon.displayName = name;",
  "  return Icon;",
  "}",
  "",
];
for (const [component, file] of Object.entries(ICONS)) {
  const svg = readFileSync(`${dir}/${file}.svg`, "utf8");
  const paths = [...svg.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
  if (paths.length !== 1) throw new Error(`${file}: expected one path, found ${paths.length}`);
  lines.push(
    `export const ${component} = make(${JSON.stringify(file)}, ${JSON.stringify(paths[0])});`,
  );
}
writeFileSync("src/components/ui/icons.tsx", lines.join("\n") + "\n");
